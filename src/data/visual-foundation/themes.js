/**
 * The 30 Visual Foundation themes. Each entry supplies a compact hue-based
 * palette (expanded into a full token set by lib/visual-foundation) plus the
 * metadata the gallery/detail views need: name, blurb, filter tags, which
 * page-content template it renders, and its default control combination
 * (see lib/visual-foundation/controls.js for what each dimension means).
 */

function theme({
  id,
  name,
  description,
  tags,
  pageType,
  dark = false,
  hue,
  accentHue = (hue + 40) % 360,
  bgHue = hue,
  paletteOverrides = {},
  defaultControls,
}) {
  const surfaceL = dark ? 15 : 97
  const textL = dark ? 93 : 17
  const mutedL = dark ? 68 : 45

  return {
    id,
    name,
    description,
    tags,
    pageType,
    dark,
    defaultControls,
    palette: {
      primary: { h: hue, s: 76, l: dark ? 63 : 53 },
      accent: { h: accentHue, s: 72, l: dark ? 65 : 55 },
      surface: { h: bgHue, s: dark ? 26 : 22, l: surfaceL },
      shadow: { h: hue, s: 55, l: dark ? 3 : 24 },
      glow: { h: hue, s: 68, l: dark ? 46 : 72 },
      bgFrom: { h: bgHue, s: dark ? 34 : 46, l: dark ? 11 : 94 },
      bgTo: { h: (bgHue + 24) % 360, s: dark ? 28 : 40, l: dark ? 6 : 89 },
      border: { h: hue, s: 38, l: dark ? 56 : 58 },
      text: { h: hue, s: dark ? 14 : 26, l: textL },
      textMuted: { h: hue, s: dark ? 9 : 14, l: mutedL },
      ...paletteOverrides,
    },
  }
}

